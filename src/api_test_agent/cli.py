from __future__ import annotations
import json
from pathlib import Path
import typer
from .planner import generate_plan
from .spec import load_document
from .runner import run_plan
from .llm import LLMPlanner
from .reliability import contract_diff, ingest_jsonl, analyze_results
from .github import create_pull_request

def build_plan(spec: str, base_url: str | None = None, use_llm: bool = False):
    result = generate_plan(spec, base_url)
    if use_llm:
        result = LLMPlanner().improve(load_document(spec), result)
    return result

app = typer.Typer(help="API Reliability Agent: contract, traffic and runtime API assurance")

@app.command()
def plan(spec: str, base_url: str | None = None, output: Path = Path("test-plan.json"), use_llm: bool = typer.Option(False, "--llm", help="Add cases with configured LLM")):
    """Generate a deterministic test plan from an OpenAPI JSON file."""
    result = build_plan(spec, base_url, use_llm)
    output.write_text(result.model_dump_json(indent=2))
    typer.echo(f"Generated {len(result.cases)} cases -> {output}")

@app.command()
def run(spec: str, base_url: str | None = None, timeout: float = 10.0, report: Path = Path("report.json"), use_llm: bool = typer.Option(False, "--llm", help="Add cases with configured LLM")):
    """Generate and execute an API test plan."""
    results = run_plan(build_plan(spec, base_url, use_llm).cases, timeout)
    report.write_text(json.dumps({"total": len(results), "passed": sum(r.passed for r in results), "results": [r.model_dump() for r in results]}, indent=2, default=str))
    for item in results: typer.echo(("PASS" if item.passed else "FAIL") + f" {item.test} ({item.duration_ms} ms)")
    typer.echo(f"Report: {report}")
    if any(not r.passed for r in results): raise typer.Exit(1)

@app.command("diff")
def diff(old: str, new: str, output: Path | None = None):
    """Detect endpoint removals between two contract versions."""
    data = contract_diff(old, new)
    text = json.dumps(data, indent=2)
    if output: output.write_text(text)
    typer.echo(text)
    if data["breaking"]: raise typer.Exit(1)

@app.command()
def ingest(log: str, output: Path = Path("traffic.jsonl")):
    """Import JSONL traffic and redact sensitive fields."""
    typer.echo(f"Ingested {ingest_jsonl(log, str(output))} records -> {output}")

@app.command()
def analyze(report: str):
    """Summarize failures and explain their risk."""
    typer.echo(json.dumps(analyze_results(report), indent=2))

@app.command("pr")
def pr(repo: str, head: str, title: str = "API reliability regression tests", body: str = "Generated by API Reliability Agent", base: str = "main", no_dry_run: bool = False):
    """Create a GitHub PR; dry-run is the safe default."""
    typer.echo(json.dumps(create_pull_request(repo, title, body, head, base, not no_dry_run), indent=2))

if __name__ == "__main__": app()
